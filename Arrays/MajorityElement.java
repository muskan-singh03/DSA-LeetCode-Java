// LeetCode: Majority Element
// Algorithm: Boyer-Moore Voting Algorithm
// Time Complexity: O(n)
// Space Complexity: O(1)

public class MajorityElement {
    public int majorityElement(int[] nums) {
        int count = 0;
        int candidate = 0;

        for (int num : nums) {
            if (count == 0) {
                candidate = num;
            }
            count += (num == candidate) ? 1 : -1;
        }
        return candidate;
    }
}
